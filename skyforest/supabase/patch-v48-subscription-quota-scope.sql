-- v48: расход месячной квоты подписки перестаёт быть общим на учётную запись.
--
-- Применяется вручную в Supabase SQL Editor, ПОСЛЕ деплоя v1.55.1 (см. порядок
-- ниже): до него прод ещё вызывает use_subscription_quota.
--
-- Что было не так. Функция из patch-v41 искала строку подписки по одному
-- user_id:
--
--   UPDATE public.user_subscriptions
--     SET identify_used = identify_used + 1, updated_at = now()
--     WHERE user_id = p_user_id
--       AND status IN ('active', 'grace', 'canceled')
--       AND current_period_end > now()
--       AND identify_used < p_limit
--     RETURNING id, identify_used INTO v_id, v_used;
--
-- Учётная запись у SkyForest, Mushroom Checker и WayBack общая, приложение
-- подписки задаётся её тиром, и колонки приложения в таблице нет — то есть
-- сузить выборку функция не могла. У пользователя с подписками в двух
-- приложениях под условие попадали обе строки, и получалось два исхода,
-- оба неверных:
--   * две подходящие строки — RETURNING ... INTO падал с P0003 «query
--     returned more than one row», вся функция откатывалась и возвращала
--     ошибку. Включённое в подписку распознавание оплачивалось токенами,
--     а в Mushroom Checker (токенов там нет) упиралось в 402;
--   * одна подходящая — расход списывался с той подписки, которая просто
--     нашлась первой, в том числе с чужого приложения, и по лимиту
--     приложения-вызывателя.
--
-- Как теперь. Строку выбирает приложение: getActiveSubscription уже отдаёт
-- подписку своего тира (по домену запроса), и consumeSubscriptionQuota
-- увеличивает счётчик атомарно только в этой строке — UPDATE по id с
-- условием на прежнее значение счётчика (см. src/lib/subscription.ts).
-- Функция в базе больше не вызывается, и оставлять её опасно: любой новый
-- вызов снова унесёт расход в чужое приложение.
--
-- Порядок выкатки (без окна, в котором распознавание падает):
--   1. деплой кода v1.55.1 — он уже не обращается к RPC, старая функция
--      остаётся в базе нетронутой;
--   2. этот патч — только после того, как прод переключился.
-- Обратный порядок оставил бы задеплоенный прод без функции на несколько
-- минут: расход квоты возвращал бы ошибку, и распознавание уходило в токены.
-- Пока патч не применён, ничего не ломается: функция просто лежит без дела.

DROP FUNCTION IF EXISTS public.use_subscription_quota(uuid, text, integer);

/**
 * Языки сборки — объединение языков всех приложений.
 *
 * Набор языков принадлежит приложению, а не сайту: словари переведены под
 * конкретный продукт, и продукты живут на разном числе языков. Но маршрут
 * `/<locale>/...` существует один на всю сборку, иначе его некому отдать даже
 * тому приложению, которому он нужен, — поэтому здесь лежит объединение, а кто
 * какие языки показывает, решает `FlavorConfig.locales`
 * (src/flavors/<id>/config.ts).
 *
 * Ровно из-за этой развилки в middleware есть увод с чужой локали: адрес
 * существует технически, но приложение языка не знает, и показывать по нему
 * заглушку на чужом языке нельзя. Middleware отправляет такой запрос на тот же
 * путь без префикса.
 *
 * Импортов здесь нет намеренно: файл читается из Edge-middleware.
 */
export const ALL_LOCALES = ["ru", "en"] as const;

export type AppLocale = (typeof ALL_LOCALES)[number];

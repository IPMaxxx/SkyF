/**
 * Подтверждение запуска службы переднего плана.
 *
 * Отдельным модулем и без единой зависимости — потому что это то самое место,
 * где приложение однажды зависало навсегда, и правило должно проверяться без
 * телефона.
 *
 * Правило: «команду приняли» и «служба работает» — разные вещи. Раньше их
 * различала нативная часть: метод плагина держал вызов, пока служба не поднимет
 * флаг. Любая заминка внутри службы превращалась при этом в отсутствие ответа —
 * Capacitor вызывает метод плагина внутри try/catch, который на исключении
 * промис не отклоняет, и «включаем запись…» жило на экране до конца похода.
 *
 * Теперь ждёт вызывающая сторона: она сама переспрашивает службу, у каждого
 * вопроса свой срок, и число вопросов конечно. Исход есть всегда.
 */

export interface ServiceSnapshot {
  running: boolean;
  /** Причина от самой службы; она падает уже после ответа на старт. */
  failure?: string | null;
}

export const CONFIRM_STEPS = 12;
export const CONFIRM_STEP_MS = 300;
/**
 * Потолок по часам, а не только по числу вопросов. Вопрос со сроком в две
 * секунды, заданный двенадцать раз, — это почти полминуты ожидания там, где
 * человек ждёт ответа «пишется путь или нет». Считать надо по часам: сколько
 * бы вопросов ни осталось, дольше этого мы не выясняем.
 */
export const CONFIRM_BUDGET_MS = 6_000;

/**
 * Переспрашивает службу, пока она не скажет «работаю» или «не смогла».
 * `ask` обязан быть со сроком: здесь его не ставят, иначе один зависший вопрос
 * вернул бы ровно ту беду, ради которой всё это написано.
 */
export async function confirmServiceStart(
  first: ServiceSnapshot,
  ask: () => Promise<ServiceSnapshot | null>,
  wait: (ms: number) => Promise<void>,
  steps: number = CONFIRM_STEPS,
  stepMs: number = CONFIRM_STEP_MS,
  budgetMs: number = CONFIRM_BUDGET_MS,
): Promise<ServiceSnapshot> {
  const began = Date.now();
  let status = first;
  for (let step = 0; step < steps; step += 1) {
    if (status.running || status.failure) return status;
    if (Date.now() - began >= budgetMs) return status;
    await wait(stepMs);
    const next = await ask();
    // Ответа на этот вопрос нет — спросим на следующем шаге, прежний ответ
    // при этом остаётся последним известным.
    if (next) status = next;
  }
  return status;
}
